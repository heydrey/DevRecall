export function buildLearningGuide(card: Card): { keyPoints: string[]; reflection: string; exercise?: ApplicationExercise } {
  // Берём целые предложения из основного объяснения, не обрезаем смысл по числу символов.
  const prose = card.answer
    .replace(/```[\s\S]*?```|~~~[\s\S]*?~~~/g, '')
    .split(/\n\s*\n/)
    .find(block => block.trim() && !/^\s*(?:#|\*\*|[-*] |\|)/.test(block)) ?? ''
  const sentences = prose.replace(/\n/g, ' ').match(/[\s\S]+?(?:[.!?](?=\s|$)|$)/g) ?? []
  const keyPoints = sentences.map(s => s.trim()).filter(s => s.length > 15).slice(0, 5)
  return {
    keyPoints: keyPoints.length ? keyPoints : ['Назовите главную идею и объясните, где она применяется.'],
    reflection: 'Объясните своими словами: почему это работает именно так? Приведите свой пример и назовите условие, при котором подход не подойдёт.',
    exercise: exercises[card.id],
  }
}
